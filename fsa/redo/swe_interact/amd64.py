"""SWE-Interact layer 1 on amd64 hosts: native task images for the multi-turn tasks.

The benchmark's own multi-turn run configs (``run_configs/multiturn/*.sh``) all pass
``--force-build``: each task image is built from ``environment/Dockerfile``, which adds
``repo_exec_server.py`` (the main container's command and health check in the task's
docker-compose.yaml) and, for rf tasks, the rubric verifier's Python dependencies. The prebuilt
``docker_image`` of task.toml is the published single-turn environment without those additions, so
it cannot start a multi-turn trial as is. On amd64 the images are built once, natively, from:

* prebuilt tasks (deepswe, rf): the published ``docker_image`` (pinned task.toml) plus the task
  Dockerfile's instructions from its ``COPY repo_exec_server.py`` line on. For rf tasks this is the
  task's own Dockerfile verbatim (it starts ``FROM`` that image); for deepswe tasks, whose
  Dockerfile rebuilds the environment from a base image with unpinned dependencies, it keeps the
  published environment (the repository at the task commit, dependencies as published) instead of
  re-resolving the dependencies today;
* build-based tasks (swebenchpro, no ``docker_image``): the task's own Dockerfile verbatim.

``amd64.patch`` (layer 1, generated by ``patch``, sha256 pinned in rungs.json) points task.toml
``docker_image`` of every task of ``patch_tasks()`` (the Stage-1 subset + the 25 swebenchpro tasks of A5.11;
A5.13 (1)) at the local tag ``image_tag(task)``, so Harbor runs the exact same image in every trial (no per-trial
rebuild) and the judges use it too. The Stage-1 layer (subset only) is ``expected_patch(subset_tasks())``, sha256
``benchmark.amd64_patch_stage1_sha256``. The arm64 layer (``arm64.patch``) does the same with arm64 rebuilds.

    python -m fsa.redo.swe_interact.amd64 patch            # (re)generate amd64.patch from the pin
    python -m fsa.redo.swe_interact.amd64 build [--tasks]  # build the native images (idempotent)
    python -m fsa.redo.swe_interact.amd64 show TASK        # the build recipe of one task
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

from .config import CLONE, PATCH_DIR, RESULTS, TASKS, load_rungs, subset_tasks

PATCH = PATCH_DIR / "amd64.patch"
REPO = "tib/swe-interact-amd64"
COPY_LINE = re.compile(r"^COPY\s+repo_exec_server\.py\s+/usr/local/bin/repo_exec_server\.py\s*$")
HEADER = ("# tib redo_v1 amd64 (fsa/redo/swe_interact/amd64.py): the published task image plus the task\n"
          "# Dockerfile's multi-turn additions (its instructions from COPY repo_exec_server.py on).\n")
ANON_DOCKER_CONFIG = RESULTS / ".docker-anon"
# Debian bullseye's security pool no longer serves python3-pip 20.3.4-4+deb11u2 and its dependencies
# (404 as of 2026-09-28 while the bullseye-security index still lists them), so the own verifier-
# dependency step of these rf tasks (Debian 11 images; ``apt-get install python3-pip``) fails. Only
# during that step apt is pinned away from bullseye-security (main-pool versions of the same
# packages); the pin file is removed right after, so the image's apt configuration is unchanged.
APT_PIN_TASKS = frozenset({"rf_task-694b4b99829f00e24fd11889", "rf_task-694b4b99829f00e24fd11891",
                           "rf_task-696719205599a51110d4b40c"})
APT_PIN_FILE = "/etc/apt/preferences.d/tib-amd64-no-bullseye-security"
# 2026-09-29: the bullseye-security pool serves no Debian 11 file at all any more (the files went
# from about 2026-09-04; the index of 2026-08-31, re-signed 2026-09-12, still lists them). Harbor's
# opencode installer runs ``apt-get install -y curl bash coreutils nodejs npm`` at trial setup when
# ``node``/``npm`` are missing, so on the two of these images without them the setup failed before
# the agent started (rf_task-...889, three attempts on W). Pinning to the main pool cannot replace
# that install (the images carry security versions, e.g. libssl1.1 deb11u2, that main-pool
# dependents do not accept), so these images get the same install at build time, with
# bullseye-security read from snapshot.debian.org at 2026-09-01, whose main/binary-amd64 index is
# byte-identical to the live one (the versions the installer would get) and whose pool is complete;
# the image's apt sources are restored afterwards. The installer then finds node/npm and skips apt,
# as it does on rf_task-...891 (node and npm are in its published image). An audit of all subset
# images (Harbor's check: ``command -v curl bash stdbuf node npm``) found one more Debian 11 image
# without node/npm, SWE-bench Pro teleport-f432a71 (three W setup failures, 2026-09-29), whose
# sources name security.debian.org; the other images that fail the check are Debian 12, Alpine or
# Ubuntu 20.04, whose repositories still serve the packages. Value: the image's bullseye-security
# source in /etc/apt/sources.list (replaced by the snapshot during the install only).
HARBOR_DEPS_TASKS = {
    "rf_task-694b4b99829f00e24fd11889": "http://deb.debian.org/debian-security",
    "rf_task-696719205599a51110d4b40c": "http://deb.debian.org/debian-security",
    "swebenchpro_instance_gravitational__teleport-f432a71a13e698b6e1c4672a2e9e9c1f32d35c12":
        "http://security.debian.org/debian-security",
}
HARBOR_DEPS = "curl bash coreutils nodejs npm"  # harbor/agents/installed/opencode.py install()
SECURITY_SNAPSHOT = "http://snapshot.debian.org/archive/debian-security/20260901T000000Z"
# Node reports the host's CPUs inside a container limited by a CPU quota: os.availableParallelism() and
# os.cpus() follow the affinity mask (Node 22.9, libuv 1.48), not the cgroup's cpu.max. Jest 29 sizes its
# worker pool from them when maxWorkers is unset (N - 1), so on this 64-CPU host rf_task-...891's
# full-suite verifier (Calypso: four Jest configs; the image sets NODE_OPTIONS=--max-old-space-size=8192)
# starts 63 workers in a container of 8 (judge) or 16 (trial) CPUs and 16 GiB, which then swaps until the
# judge's 5400 s timeout (the revalidation's reference run, 2026-09-29). A host with as many CPUs as the
# container's quota would start quota - 1 workers; this image preloads a module (NODE_OPTIONS --require,
# appended to the image's value) that makes both calls report the quota (cgroup v2 cpu.max; unchanged
# when unlimited or unreadable). No other subset task's tests size a worker pool from Node's CPU count.
NODE_CPU_QUOTA_TASKS = frozenset({"rf_task-694b4b99829f00e24fd11891"})
NODE_CPU_QUOTA_JS = "/opt/tib/node-cpu-quota.js"
NODE_CPU_QUOTA_SRC = """\
// tib redo_v1 amd64 (fsa/redo/swe_interact/amd64.py NODE_CPU_QUOTA_TASKS): report the container's CPU
// quota (cgroup v2 cpu.max) as its CPU count, as a host with that many CPUs would.
'use strict';
try {
  var os = require('os');
  var q = require('fs').readFileSync('/sys/fs/cgroup/cpu.max', 'utf8').trim().split(/\\s+/);
  var n = q[0] === 'max' ? 0 : Math.max(1, Math.floor(Number(q[0]) / Number(q[1] || 100000)));
  if (n > 0 && n < os.cpus().length) {
    var cpus = os.cpus;
    os.cpus = function () { return cpus.call(os).slice(0, n); };
    if (typeof os.availableParallelism === 'function') {
      var ap = os.availableParallelism;
      os.availableParallelism = function () { return Math.min(ap.call(os), n); };
    }
  }
} catch (e) {}
"""


def _with_apt_pin(dockerfile: str) -> str:
    """The Dockerfile with the bullseye-security pin around its first RUN after the COPY line."""
    lines = dockerfile.splitlines(keepends=True)
    copy = [i for i, ln in enumerate(lines) if COPY_LINE.match(ln.strip())][0]
    run = next(i for i in range(copy + 1, len(lines)) if lines[i].startswith("RUN "))
    pin = ("# tib redo_v1 amd64: bullseye-security no longer serves the packages this step installs; pin apt\n"
           "# to the main-pool versions for this step only (fsa/redo/swe_interact/amd64.py APT_PIN_TASKS).\n"
           f"RUN printf 'Package: *\\nPin: release n=bullseye-security\\nPin-Priority: -1\\n' > {APT_PIN_FILE}\n")
    tail = "" if dockerfile.endswith("\n") else "\n"
    return "".join(lines[:run]) + pin + "".join(lines[run:]) + tail + f"RUN rm -f {APT_PIN_FILE}\n"


def _with_harbor_deps(dockerfile: str, source: str) -> str:
    """The Dockerfile plus Harbor's opencode system dependencies (bullseye-security, named ``source`` in
    the image's sources.list, read from its snapshot)."""
    tail = "" if dockerfile.endswith("\n") else "\n"
    return (dockerfile + tail
            + "# tib redo_v1 amd64 (2026-09-29): Harbor's opencode installer would apt-install these at trial setup;\n"
              "# bullseye-security's pool is gone, so they are installed here from its snapshot (same index) and the\n"
              "# apt sources are restored (fsa/redo/swe_interact/amd64.py HARBOR_DEPS_TASKS).\n"
              "RUN cp /etc/apt/sources.list /tmp/tib-sources.list \\\n"
              f" && sed -i -E 's#^deb {source} #deb {SECURITY_SNAPSHOT} #' /etc/apt/sources.list \\\n"
              " && apt-get -o Acquire::Check-Valid-Until=false update \\\n"
              f" && DEBIAN_FRONTEND=noninteractive apt-get install -y {HARBOR_DEPS} \\\n"
              " && mv /tmp/tib-sources.list /etc/apt/sources.list \\\n"
              " && node --version && npm --version\n")


def _with_node_cpu_quota(dockerfile: str) -> str:
    """The Dockerfile plus the Node CPU-quota preload (``NODE_CPU_QUOTA_SRC``), appended to NODE_OPTIONS."""
    tail = "" if dockerfile.endswith("\n") else "\n"
    return (dockerfile + tail
            + "# tib redo_v1 amd64 (2026-09-29): Node reports the host's CPUs, not the container's quota, so Jest\n"
              "# would start (host CPUs - 1) workers; report the quota (fsa/redo/swe_interact/amd64.py NODE_CPU_QUOTA_TASKS).\n"
              f"COPY <<'TIB_EOF' {NODE_CPU_QUOTA_JS}\n" + NODE_CPU_QUOTA_SRC + "TIB_EOF\n"
              f'ENV NODE_OPTIONS="${{NODE_OPTIONS}} --require {NODE_CPU_QUOTA_JS}"\n'
              f"RUN node -e \"require('os').cpus()\" && echo \"NODE_OPTIONS=$NODE_OPTIONS\"\n")


def _git(*args: str, env: dict | None = None, stdin: str | None = None) -> str:
    r = subprocess.run(["git", "-C", str(CLONE), *args], capture_output=True, text=True, input=stdin,
                       env={**os.environ, **(env or {})})
    if r.returncode not in (0, 1):
        raise SystemExit(f"git {' '.join(args)} failed: {r.stderr}")
    return r.stdout


def _pin() -> str:
    return load_rungs()["benchmark"]["commit"]


def _rel(task: str) -> str:
    return f"data/multiturn/{task}"


def published_image(task: str) -> str | None:
    """task.toml ``environment.docker_image`` at the pin (the benchmark's published image), or None."""
    toml = _git("show", f"{_pin()}:{_rel(task)}/task.toml")
    return tomllib.loads(toml)["environment"].get("docker_image") or None


def image_tag(task: str) -> str:
    """The local image of a task on amd64 (Docker tags hold at most 128 characters)."""
    tag = task if len(task) <= 128 else f"{task[:119]}-{hashlib.sha256(task.encode()).hexdigest()[:8]}"
    return f"{REPO}:{tag}"


def recipe(task: str) -> dict:
    """``{"kind", "base", "dockerfile", "dockerfile_sha256"}``: how ``image_tag(task)`` is built
    (context: the task's ``environment/`` directory)."""
    own = _git("show", f"{_pin()}:{_rel(task)}/environment/Dockerfile")
    froms = [ln.split()[1] for ln in own.splitlines() if ln.strip().upper().startswith("FROM ") and len(ln.split()) > 1]
    pub = published_image(task)
    if pub is None or froms == [pub]:
        kind, text, base = "task_dockerfile", own, (froms[-1] if froms else None)
    else:
        lines = own.splitlines(keepends=True)
        idx = [i for i, ln in enumerate(lines) if COPY_LINE.match(ln.strip())]
        if len(idx) != 1:
            raise SystemExit(f"{task}: expected exactly one 'COPY repo_exec_server.py' line in its Dockerfile, found {len(idx)}")
        kind, text, base = "published_image_plus_multiturn_additions", HEADER + f"FROM {pub}\n\n" + "".join(lines[idx[0]:]), pub
    if task in APT_PIN_TASKS:
        kind, text = kind + "+bullseye_security_pin", _with_apt_pin(text)
    if task in HARBOR_DEPS_TASKS:
        kind, text = kind + "+harbor_deps_snapshot", _with_harbor_deps(text, HARBOR_DEPS_TASKS[task])
    if task in NODE_CPU_QUOTA_TASKS:
        kind, text = kind + "+node_cpu_quota", _with_node_cpu_quota(text)
    return {"kind": kind, "base": base, "dockerfile": text,
            "dockerfile_sha256": hashlib.sha256(text.encode()).hexdigest()}


def retag(toml_text: str, tag: str) -> str:
    """Set ``[environment] docker_image`` (replace the value, or add the key under the header)."""
    lines = toml_text.splitlines(keepends=True)
    sec = None
    for i, ln in enumerate(lines):
        s = ln.strip()
        if s.startswith("["):
            sec = s
        elif sec == "[environment]" and re.match(r"^docker_image\s*=", s):
            lines[i] = f'docker_image = "{tag}"\n'
            return "".join(lines)
    for i, ln in enumerate(lines):
        if ln.strip() == "[environment]":
            lines.insert(i + 1, f'docker_image = "{tag}"\n')
            return "".join(lines)
    raise SystemExit("task.toml has no [environment] section")


SWEBENCHPRO_PREFIX = "swebenchpro_"
N_SWEBENCHPRO = 25   # A5.11 (3): every swebenchpro_* task of the benchmark


def swebenchpro_tasks() -> list[str]:
    """Every ``data/multiturn/swebenchpro_*`` task at the pin (the A5.11 task list before exclusions)."""
    names = _git("ls-tree", "--name-only", f"{_pin()}:data/multiturn").split()
    out = sorted(n for n in names if n.startswith(SWEBENCHPRO_PREFIX))
    if len(out) != N_SWEBENCHPRO:
        raise SystemExit(f"expected {N_SWEBENCHPRO} swebenchpro tasks at the pin, found {len(out)}")
    return out


def patch_tasks() -> list[str]:
    """The tasks layer 1 retags (A5.13 (1)): the Stage-1 effective subset (20) + the 25 swebenchpro tasks of A5.11
    (7 overlap) = 38. ``expected_patch(subset_tasks())`` is the Stage-1 layer (sha ``amd64_patch_stage1_sha256``)."""
    return sorted(set(subset_tasks()) | set(swebenchpro_tasks()))


def expected_patch(tasks: list[str] | None = None) -> str:
    """Layer 1 as generated from the pin: task.toml ``docker_image`` -> ``image_tag`` for ``tasks`` (default
    ``patch_tasks()``)."""
    pin = _pin()
    with tempfile.TemporaryDirectory() as td:
        env = {"GIT_INDEX_FILE": str(Path(td) / "index")}
        _git("read-tree", pin, env=env)
        for task in sorted(tasks or patch_tasks()):
            rel = f"{_rel(task)}/task.toml"
            new = retag(_git("show", f"{pin}:{rel}"), image_tag(task))
            blob = _git("hash-object", "-w", "--stdin", stdin=new).strip()
            _git("update-index", "--cacheinfo", f"100644,{blob},{rel}", env=env)
        return _git("diff", "--cached", pin, env=env)


def image_state(task: str) -> dict:
    """Whether ``image_tag(task)`` exists locally, built from the current recipe."""
    tag = image_tag(task)
    r = subprocess.run(["docker", "image", "inspect", tag, "--format",
                        "{{.Id}} {{.Architecture}} {{index .Config.Labels \"tib.recipe_sha256\"}}"],
                       capture_output=True, text=True)
    parts = r.stdout.split()
    return {"image": tag, "exists": r.returncode == 0, "image_id": parts[0] if parts else None,
            "arch": parts[1] if len(parts) > 1 else None, "recipe_sha256": parts[2] if len(parts) > 2 else None}


def build(task: str, arch: str = "amd64") -> dict:
    """Build ``image_tag(task)`` natively (base images pulled anonymously); labels record the recipe."""
    rc = recipe(task)
    ANON_DOCKER_CONFIG.mkdir(parents=True, exist_ok=True)
    (ANON_DOCKER_CONFIG / "config.json").write_text("{}")
    r = subprocess.run(["docker", "build", "--platform", f"linux/{arch}", "-t", image_tag(task),
                        "--label", f"tib.recipe_sha256={rc['dockerfile_sha256']}", "--label", f"tib.recipe_kind={rc['kind']}",
                        "-f", "-", str(TASKS / task / "environment")], input=rc["dockerfile"], capture_output=True,
                       text=True, env={**os.environ, "DOCKER_CONFIG": str(ANON_DOCKER_CONFIG)})
    return {"task": task, "image": image_tag(task), "built": r.returncode == 0, "kind": rc["kind"],
            "recipe_sha256": rc["dockerfile_sha256"], "log_tail": (r.stdout + r.stderr)[-1500:]}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("cmd", choices=["patch", "build", "show"])
    ap.add_argument("task", nargs="?")
    ap.add_argument("--tasks", default=None, help="comma-separated tasks (build; default: patch_tasks(), the 38 "
                                                  "tasks layer 1 retags)")
    ap.add_argument("--force", action="store_true", help="build even when the image exists from the current recipe")
    a = ap.parse_args(argv)
    if a.cmd == "patch":
        text = expected_patch()
        PATCH.write_text(text)
        print(f"wrote {PATCH} ({len(text)} bytes, sha256 {hashlib.sha256(text.encode()).hexdigest()}); "
              "pin it as benchmark.amd64_patch_sha256 in rungs.json")
        return 0
    if a.cmd == "show":
        rc = recipe(a.task)
        print(json.dumps({k: v for k, v in rc.items() if k != "dockerfile"}, indent=1))
        print(rc["dockerfile"])
        return 0
    tasks = a.tasks.split(",") if a.tasks else patch_tasks()
    bad = 0
    for t in tasks:
        st = image_state(t)
        if st["exists"] and st["recipe_sha256"] == recipe(t)["dockerfile_sha256"] and not a.force:
            print(json.dumps({"task": t, "image": st["image"], "built": False, "present": True}), flush=True)
            continue
        res = build(t)
        bad += not res["built"]
        print(json.dumps(res if not res["built"] else {k: v for k, v in res.items() if k != "log_tail"}), flush=True)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
